def create_version(translations, suffix, lang_name):
    """创建翻译版本"""
    print(f"创建 {lang_name} 版本...")

    source_file = BASE_DIR / 'index.html'
    target_file = BASE_DIR / f'index-{suffix}.html'

    with open(source_file, 'r', encoding='utf-8') as f:
        content = f.read()

    # 应用翻译
    for cn, trans in translations.items():
        content = content.replace(cn, trans)

    with open(target_file, 'w', encoding='utf-8') as f:
        f.write(content)

    print(f"  ✅ 创建: index-{suffix}.html")

